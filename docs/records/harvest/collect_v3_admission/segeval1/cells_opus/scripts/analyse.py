"""Size-vs-output tables for census, W1, 888, 150. Writes size_vs_output.md and analysis.json."""
import gzip, json, sys
from collections import Counter, defaultdict
from pathlib import Path
import numpy as np

SP = Path(sys.argv[1]); OUTD = Path(sys.argv[2])
TYPES = ['numeric', 'mixed', 'non-numeric']
Q = [10, 25, 50, 75, 90]


def load():
    pops = defaultdict(list)
    with gzip.open(SP / 'census_compact.tsv.gz', 'rt') as f:
        next(f)
        for line in f:
            p = line.rstrip('\n').split('\t')
            r = dict(line_id=p[0], wave=p[1], source=p[2], primary_class=p[3], width=int(p[5]), height=int(p[6]),
                     chars=int(p[7]), output_type=p[9], verdict_05=None if p[10] == 'None' else p[10], reason_05=p[11])
            pops['census'].append(r)
            if r['wave'] == 'W1':
                pops['W1'].append(r)
    for line in open(SP / 'small_pops.jsonl'):
        r = json.loads(line)
        pops[r['population']].append(r)
    return pops


def qrow(x):
    x = np.asarray(x, float)
    if not len(x):
        return ['–'] * 5
    return [f'{v:.2f}' for v in np.percentile(x, Q)]


def fit(ch, ra):
    ch = np.asarray(ch, float); ra = np.asarray(ra, float)
    if len(ch) < 3 or np.ptp(ch) == 0:
        return None
    a, b = np.polyfit(ch, ra, 1)
    res = ra - (a * ch + b)
    med = {}
    for c in np.unique(ch):
        m = ch == c
        if m.sum() >= 10:
            med[int(c)] = float(np.median(ra[m]))
    mf = np.polyfit(list(med), list(med.values()), 1) if len(med) >= 3 else None
    return dict(n=int(len(ch)), a=float(a), b=float(b), resid_sd=float(res.std(ddof=2)),
                resid_mad=float(np.median(np.abs(res - np.median(res)))), resid_p10=float(np.percentile(res, 10)),
                resid_p90=float(np.percentile(res, 90)), r2=float(1 - res.var() / ra.var()) if ra.var() > 0 else None,
                median_ratio_per_char=float(np.median(ra / ch)),
                median_fit_a=float(mf[0]) if mf is not None else None, median_fit_b=float(mf[1]) if mf is not None else None,
                median_fit_points=len(med))


def main():
    pops = load()
    out = []; js = {}
    w = out.append
    w('# Crop size vs Google output, short crops vs text lines\n')
    w('Generated by `scripts/analyse.py` (read-only). Definitions:\n')
    w('- chars = non-space NFC codepoints of the Google text (`sum(not c.isspace())`). On the census this equals the filter\'s saved count (which also drops combining marks/controls) on 592,416 of 592,466 rows.')
    w('- ratio = crop width_px / crop height_px (original crop pixels; for the 150 and 888 `after.frame.source_width/source_height`, identical to the census dimensions for all 1,038 rows).')
    w('- numeric = stripped text is only digits + `. , : ; / - – — % ( ) + \' ′ § № °` + spaces with at least one digit, or one canonical upper-case Latin Roman numeral (regex `M{0,3}(CM|CD|D?C{0,3})(XC|XL|L?X{0,3})(IX|IV|V?I{0,3})`) with an optional trailing `.` or `)`. mixed = not numeric, ≥1 digit and ≤2 letters (Unicode L*), e.g. `12α`, `Αρ. 7`, also digits with an unlisted symbol such as `12*` (0 letters). non-numeric = everything else (incl. punctuation-only, Greek-iota `ΙΙ`, lower-case Roman). Note `§ 5` is numeric by the given separator list.')
    w('- vertical = height > width; excluded from every size table and fit, counted separately.')
    w('- short = chars ≤ 9 (rows 1..15 shown so the ≤5 / ≤9 / ≤15 cuts are visible); long = chars ≥ 10.')
    w('- quantiles: numpy linear-interpolation percentiles. Fit: ordinary least squares `ratio = a·chars + b` on every row; "median fit" = least squares through the per-chars median ratios (chars values with n ≥ 10). Residual spread = SD (ddof 2), MAD, and p10/p90 of residuals.\n')
    order = ['census', 'W1', '888', '150']
    sizes = {p: len(pops[p]) for p in order}
    w('Populations: ' + ', '.join(f'{p} n={sizes[p]:,}' for p in order) + '. W1 = census rows with wave `W1` (the census reduced from the W1 features snapshot of 2026-10-18 05:24).\n')
    for pop in order:
        rows = pops[pop]; J = js[pop] = {}
        vert = [r for r in rows if r['height'] > r['width']]
        hz = [r for r in rows if r['height'] <= r['width'] and r['width'] > 0 and r['height'] > 0]
        w(f'\n## Population: {pop} (n={len(rows):,})\n')
        vc = Counter((r['output_type'], 'short' if r['chars'] <= 9 else 'long') for r in vert)
        w(f'Vertical crops excluded: {len(vert):,} ({100*len(vert)/len(rows):.2f}%); of these short numeric {vc[("numeric","short")]:,}, short mixed {vc[("mixed","short")]:,}, short non-numeric {vc[("non-numeric","short")]:,}, long {sum(v for k,v in vc.items() if k[1]=="long"):,}.\n')
        J['vertical'] = {f'{a}|{b}': v for (a, b), v in vc.items()}; J['n'] = len(rows); J['n_vertical'] = len(vert)
        by = defaultdict(list)
        for r in hz:
            by[(r['output_type'], r['chars'])].append(r)
        w('### A1. Ratio (width/height) per character count, short crops\n')
        for t in TYPES:
            tot = sum(len(by[(t, c)]) for c in range(1, 10))
            w(f'\n**{t}** (chars 1–9, non-vertical: n={tot:,})\n')
            w('| chars | n | p10 | p25 | p50 | p75 | p90 | median ratio/char |')
            w('|---:|---:|---:|---:|---:|---:|---:|---:|')
            for c in range(1, 16):
                xs = [r['width'] / r['height'] for r in by[(t, c)]]
                if not xs and c > 9:
                    continue
                mark = ' (≤5 cut)' if c == 5 else ' (≤9 cut)' if c == 9 else ' (≤15 cut)' if c == 15 else ''
                rpc = f'{np.median(np.array(xs)/c):.3f}' if xs else '–'
                w(f'| {c}{mark} | {len(xs):,} | ' + ' | '.join(qrow(xs)) + f' | {rpc} |')
                J.setdefault('short_quantiles', {}).setdefault(t, {})[c] = dict(n=len(xs), q=qrow(xs))
        w('\n**Long reference (chars ≥ 10)**\n')
        w('| type | chars bin | n | p10 | p25 | p50 | p75 | p90 | median ratio/char |')
        w('|---|---|---:|---:|---:|---:|---:|---:|---:|')
        for t in TYPES:
            for lo, hi in [(10, 19), (20, 39), (40, 10**6)]:
                sel = [r for r in hz if r['output_type'] == t and lo <= r['chars'] <= hi]
                xs = [r['width'] / r['height'] for r in sel]
                rpc = f'{np.median([r["width"]/r["height"]/r["chars"] for r in sel]):.3f}' if sel else '–'
                lab = f'{lo}–{hi}' if hi < 10**6 else f'{lo}+'
                w(f'| {t} | {lab} | {len(xs):,} | ' + ' | '.join(qrow(xs)) + f' | {rpc} |')
        # pixel sizes
        w('\n**A1b. Pixel sizes of short crops (non-vertical), width and height px quantiles p10/p50/p90**\n')
        w('| type | chars | n | width p10 | width p50 | width p90 | height p10 | height p50 | height p90 |')
        w('|---|---|---:|---:|---:|---:|---:|---:|---:|')
        for t in TYPES:
            for lab, lo, hi in [('1–3', 1, 3), ('4–6', 4, 6), ('7–9', 7, 9), ('10–19', 10, 19), ('20+', 20, 10**6)]:
                sel = [r for r in hz if r['output_type'] == t and lo <= r['chars'] <= hi]
                if not sel:
                    w(f'| {t} | {lab} | 0 | – | – | – | – | – | – |'); continue
                ws = np.percentile([r['width'] for r in sel], [10, 50, 90]); hs = np.percentile([r['height'] for r in sel], [10, 50, 90])
                w(f'| {t} | {lab} | {len(sel):,} | ' + ' | '.join(f'{v:.0f}' for v in ws) + ' | ' + ' | '.join(f'{v:.0f}' for v in hs) + ' |')
        # A2 fits
        w('\n### A2. Linear fit ratio = a·chars + b\n')
        w('| group | n | a (OLS) | b (OLS) | resid SD | resid MAD | resid p10 | resid p90 | R² | median ratio/char | a (median fit) | b (median fit) |')
        w('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
        groups = []
        for t in TYPES:
            for cut in (5, 9, 15):
                groups.append((f'short {t} chars≤{cut}', [r for r in hz if r['output_type'] == t and r['chars'] <= cut]))
        groups.append(('long non-numeric (text lines) chars≥10', [r for r in hz if r['output_type'] == 'non-numeric' and r['chars'] >= 10]))
        groups.append(('long non-numeric chars 10–60', [r for r in hz if r['output_type'] == 'non-numeric' and 10 <= r['chars'] <= 60]))
        groups.append(('long numeric chars≥10', [r for r in hz if r['output_type'] == 'numeric' and r['chars'] >= 10]))
        groups.append(('all non-vertical rows', hz))
        J['fits'] = {}
        for name, sel in groups:
            f = fit([r['chars'] for r in sel], [r['width'] / r['height'] for r in sel])
            J['fits'][name] = f
            if not f:
                w(f'| {name} | {len(sel)} | – | – | – | – | – | – | – | – | – | – |'); continue
            mf = (f'{f["median_fit_a"]:.3f} | {f["median_fit_b"]:.3f}') if f['median_fit_a'] is not None else '– | –'
            w(f'| {name} | {f["n"]:,} | {f["a"]:.3f} | {f["b"]:.3f} | {f["resid_sd"]:.3f} | {f["resid_mad"]:.3f} | {f["resid_p10"]:.3f} | {f["resid_p90"]:.3f} | {f["r2"]:.3f} | {f["median_ratio_per_char"]:.3f} | {mf} |')
        # A3 filter treatment
        w('\n### A3. How the 0.5 filter treated short crops (chars ≤ 9, non-vertical)\n')
        cats = Counter(); 
        for r in hz:
            if r['chars'] <= 9:
                rc = r.get('reason_05') or (r['verdict_05'] or 'NOT_EVALUATED')
                if r['verdict_05'] and not rc.startswith(r['verdict_05']):
                    rc = r['verdict_05'] + ' (reason n/a)'
                cats[(r['output_type'], rc)] += 1
        for r in hz:
            if r['chars'] >= 10:
                rc = r.get('reason_05') or (r['verdict_05'] or 'NOT_EVALUATED')
                if r['verdict_05'] and not rc.startswith(r['verdict_05']):
                    rc = r['verdict_05'] + ' (reason n/a)'
                cats[('long (≥10, all types)', rc)] += 1
        rcs = sorted({k[1] for k in cats}, key=lambda s: (not s.startswith('KEEP'), not s.startswith('DROP'), s))
        cols = TYPES + ['long (≥10, all types)']
        w('| 0.5 verdict / reason | ' + ' | '.join(cols) + ' |')
        w('|---|' + '---:|' * len(cols))
        tot = {c: sum(v for k, v in cats.items() if k[0] == c) for c in cols}
        for rc in rcs:
            w(f'| {rc} | ' + ' | '.join(f'{cats[(c, rc)]:,} ({100*cats[(c, rc)]/tot[c]:.1f}%)' if tot[c] else '0' for c in cols) + ' |')
        w('| total | ' + ' | '.join(f'{tot[c]:,}' for c in cols) + ' |')
        J['filter_05'] = {f'{a}|{b}': v for (a, b), v in cats.items()}
        if pop in ('150', '888'):
            good = 'fine' if pop == '150' else 'KEEP'
            rated = [r for r in rows if r['owner'] is not None]
            w(f'\n**False rejects on the {pop}** (owner {"standard state = fine" if pop=="150" else "rating = KEEP"} and filter verdict DROP). Owner-judged rows: {len(rated)} (owner states: {dict(Counter(r["owner"] for r in rated))}).\n')
            w('| group | owner-good n | 0.5 DROP | 0.8 DROP | 0.5 UNCERTAIN | 0.8 UNCERTAIN |')
            w('|---|---:|---:|---:|---:|---:|')
            J['false_rejects'] = {}
            def grp(r):
                if r['height'] > r['width']:
                    return 'vertical (any)'
                return f'short {r["output_type"]}' if r['chars'] <= 9 else 'long (≥10)'
            gs = ['short numeric', 'short mixed', 'short non-numeric', 'long (≥10)', 'vertical (any)']
            for g in gs + ['all']:
                sel = [r for r in rows if r['owner'] == good and (g == 'all' or grp(r) == g)]
                v = dict(n=len(sel), d05=sum(r['verdict_05'] == 'DROP' for r in sel), d08=sum(r['verdict_08'] == 'DROP' for r in sel),
                         u05=sum(r['verdict_05'] == 'UNCERTAIN' for r in sel), u08=sum(r['verdict_08'] == 'UNCERTAIN' for r in sel))
                J['false_rejects'][g] = v
                w(f'| {g} | {v["n"]} | {v["d05"]} | {v["d08"]} | {v["u05"]} | {v["u08"]} |')
            fr = [r for r in rows if r['owner'] == good and 'DROP' in (r['verdict_05'], r['verdict_08']) and r['chars'] <= 15]
            if fr:
                w(f'\nShort (chars ≤ 15) owner-good rows dropped by 0.5 or 0.8:\n')
                w('| line_id | text | w×h | ratio | chars | type | 0.5 | 0.8 | 0.8 reason |')
                w('|---|---|---|---:|---:|---|---|---|---|')
                for r in sorted(fr, key=lambda r: (r['chars'], r['line_id'])):
                    w(f'| {r["line_id"]} | `{r["text"]}` | {r["width"]}×{r["height"]} | {r["width"]/r["height"]:.2f} | {r["chars"]} | {r["output_type"]} | {r["verdict_05"]} | {r["verdict_08"]} | {r["reason_08"][:70]} |')
            # also bad rows that are short
            bad = 'faulty' if pop == '150' else 'DROP'
            sb = Counter(grp(r) for r in rows if r['owner'] == bad)
            w(f'\nOwner-bad rows ({bad}) by group: ' + ', '.join(f'{g} {sb[g]}' for g in gs) + '.')
        # A4 counts by source / class (census only, and W1)
        if pop in ('census', 'W1'):
            for axis in ('source', 'primary_class'):
                w(f'\n### A4. Short crops (chars ≤ 9) by {axis}, {pop}\n')
                cnt = defaultdict(Counter)
                for r in rows:
                    k = r[axis]
                    cnt[k]['all'] += 1
                    if r['chars'] <= 9:
                        if r['height'] > r['width']:
                            cnt[k]['vertical'] += 1
                        else:
                            cnt[k][r['output_type']] += 1
                keys = sorted(cnt, key=lambda k: -(cnt[k]['numeric'] + cnt[k]['mixed'] + cnt[k]['non-numeric']))
                w(f'| {axis} | all rows | short numeric | short mixed | short non-numeric | short vertical (excluded) | short share of rows |')
                w('|---|---:|---:|---:|---:|---:|---:|')
                tot = Counter()
                for k in keys:
                    c = cnt[k]; s = c['numeric'] + c['mixed'] + c['non-numeric'] + c['vertical']
                    tot.update(c)
                    if s == 0:
                        continue
                    w(f'| {k} | {c["all"]:,} | {c["numeric"]:,} | {c["mixed"]:,} | {c["non-numeric"]:,} | {c["vertical"]:,} | {100*s/c["all"]:.1f}% |')
                zero = [k for k in keys if cnt[k]['numeric'] + cnt[k]['mixed'] + cnt[k]['non-numeric'] + cnt[k]['vertical'] == 0]
                s = tot['numeric'] + tot['mixed'] + tot['non-numeric'] + tot['vertical']
                w(f'| **total** | {tot["all"]:,} | {tot["numeric"]:,} | {tot["mixed"]:,} | {tot["non-numeric"]:,} | {tot["vertical"]:,} | {100*s/tot["all"]:.1f}% |')
                if zero:
                    w(f'\n{len(zero)} {axis} values with no short crop: ' + ', '.join(f'{k} ({cnt[k]["all"]:,})' for k in zero) + '.')
                J[f'by_{axis}'] = {k: dict(v) for k, v in cnt.items()}
    (OUTD / 'size_vs_output.md').write_text('\n'.join(out) + '\n')
    (OUTD / 'analysis.json').write_text(json.dumps(js, ensure_ascii=False, indent=1, default=str) + '\n')
    for p in order:
        f = js[p]['fits']
        print(p, {k: (round(v['a'], 3), round(v['b'], 3), v['n']) if v else None for k, v in f.items()})


main()
