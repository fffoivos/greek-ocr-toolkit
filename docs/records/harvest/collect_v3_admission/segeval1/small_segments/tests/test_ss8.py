def test_reweighting_arithmetic():
    sample=[dict(source='a',kind='yes'),dict(source='a',kind='no'),dict(source='b',kind='yes')]
    got=s.weighted(sample,{'a':20,'b':80},'kind',['yes','no'])
    assert got[0]['weighted_share']==.9
    assert got[1]['weighted_share']==.1
    assert got[0]['estimated_pool_rows']==90
    assert got[0]['unweighted_share']==2/3
    assert sum(r['weighted_share'] for r in got)==1
    assert got[0]['wilson95_unweighted']==s.q3.wilson(2,3)
    # Delete the b row and its entire pool: surviving share becomes 1/2.
    after=s.weighted(sample[:2],{'a':20,'b':0},'kind',['yes','no'])
    assert after[0]['weighted_share']==.5
    with pytest.raises(ValueError,match='No surviving sample'):
        s.weighted(sample[:2],{'a':20,'b':80},'kind',['yes','no'])


def test_filtered_pool_and_counts():
    ids=s.load(SS/'gate_recheck/foreign_mixed_ids_20261019.json');exclude=set(ids['foreign'])|set(ids['mixed'])
    sample=s.rows(SS/'samples.jsonl');v1=s.rows(SS/'small_population_key.jsonl.gz');marks=s.rows(SS/'owner_marks_smallseg.jsonl')
    result=s.compute_q3(sample,v1,marks,exclude)
    original=s.load(SS/'q3/SS3_RECEIPT.json')['pools']['inside_by_source']['by_source']
    for source,n in original.items():
        removed=sum(r['row_id'] in exclude and r['source']==source and r['output_type'] in {'mixed','nonnumeric'} for r in v1)
        assert result['source_pools'][source]==n-removed
    assert result['n']==sum(not r['control'] and r['stratum']=='inside_by_source' and r['line_id'] not in exclude for r in sample)
    for values in result['T8'].values():
        assert sum(r['n'] for r in values)==result['n']
        assert sum(r['weighted_share'] for r in values)==pytest.approx(1)
        assert sum(r['estimated_pool_rows'] for r in values)==pytest.approx(result['pool_total'])
    assert s.load(SS/'gate_recheck/Q3_GATE.json')['after']==result


