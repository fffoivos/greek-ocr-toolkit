def test_deterministic_gzip_and_serialization(tmp_path):
    source=tmp_path/'source.gz'
    # Noncanonical spelling must survive rather than being parsed/reserialized.
    with gzip.open(source,'wb') as f: f.write(b'{"row_id": "both", "value": 1.2300, "s": "\\u03b1"}\n')
    a,b=tmp_path/'a.gz',tmp_path/'b.gz'
    key.build({'both'},{'both'},source,a);key.build({'both'},{'both'},source,b)
    assert a.read_bytes()==b.read_bytes()
    assert b'1.2300' in gzip.decompress(a.read_bytes())


